document.addEventListener("DOMContentLoaded", () => {
    const popupZamkniety = localStorage.getItem("popupZamkniety");
    if (!popupZamkniety) {
        const popup = document.getElementById("popup");
        popup.style.display = "flex";
        document.body.classList.add("no-scroll");
        document.documentElement.classList.add("no-scroll");
    }
    document.getElementById("typy").classList.add("aktywna");
    wyswietlKwiaty();
    ustawAutouzupełnianie();
    ustawWyszukiwanie();
});
// popup ---------
function zamknijPopup() {
    document.getElementById("popup").style.display = "none";
    localStorage.setItem("popupZamkniety", "true");
    document.body.classList.remove("no-scroll");
    document.documentElement.classList.remove("no-scroll");
}
// wyświetlanie kwiatów ---------
function wyswietlKwiaty(lista = kwiaty) {
    const container = document.getElementById("kwiaty-container");
    container.innerHTML = "";
    lista
        .sort((a, b) => a.nazwa.localeCompare(b.nazwa))
        .forEach(kwiat => {
            const karta = document.createElement("div");
            karta.classList.add("karta");
            karta.innerHTML = `
                <img src="${kwiat.obraz}" alt="${kwiat.nazwa}">
                <div class="karta-content">
                    <h2>${kwiat.nazwa}</h2>
                    <p><strong>Smak:</strong> ${kwiat.smak}</p>
                    <p><strong>Kwitnienie:</strong> ${kwiat.kwitnienie}</p>
                </div>
            `;
            karta.addEventListener("click", () => {
                pokazPopupKwiatu(kwiat);
            });
            container.appendChild(karta);
        });
}
// autouzupełnianie ---------
function ustawAutouzupełnianie() {
    const lista = document.getElementById("kwiaty-lista");
    lista.innerHTML = "";
    kwiaty.forEach(k => {
        const option = document.createElement("option");
        option.value = k.nazwa;
        lista.appendChild(option);
    });
}
// wyszukiwanie ---------
function ustawWyszukiwanie() {
    const input = document.getElementById("szukaj");
    input.addEventListener("input", function () {
        const tekst = this.value.toLowerCase();
        const przefiltrowane = kwiaty.filter(k =>
            k.nazwa.toLowerCase().includes(tekst)
        );
        wyswietlKwiaty(przefiltrowane);
    });
}
// popup kwiatu ---------
function pokazPopupKwiatu(kwiat) {
    document.body.classList.add("zamrozone", "kwiat-tryb");
    document.getElementById("popup-img").src = kwiat.obraz;
    document.getElementById("popup-nazwa").textContent = kwiat.nazwa;
    document.getElementById("popup-smak").innerHTML =
        "<strong>Smak:</strong> " + kwiat.smak;
    document.getElementById("popup-kwitnienie").innerHTML =
        "<strong>Kwitnienie:</strong> " + kwiat.kwitnienie;
    document.getElementById("popup-przygotowanie").innerHTML =
        "<strong>Sposoby spożycia:</strong><ul>" +
        kwiat.przygotowanie.map(item => `<li>${item}</li>`).join("") +
        "</ul>";
    document.getElementById("popup-kwiat").style.display = "block";
}
// zamknięcie popupu kwiatu ---------
